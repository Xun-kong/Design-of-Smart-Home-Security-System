void OLED_SetCursor(uint8_t X, uint8_t Page)
{
	OLED_WriteCommand(0x00 | (X & 0x0F));
	OLED_WriteCommand(0x10 | ((X & 0xF0) >> 4));
	OLED_WriteCommand(0xB0 | Page);
}

void OLED_Clear(void)
{
	for (uint8_t j = 0; j < 8; j ++)
	{
		OLED_SetCursor(0, j);
		for (uint8_t i = 0; i < 128; i ++)
		{
			OLED_WriteData(0x00);
		}
	}
}

void OLED_ShowChar(uint8_t X, uint8_t Page, char Char, uint8_t FontSize,uint8_t mode)
{
	
	if (FontSize == 6)
	{
		OLED_SetCursor(X, Page);
		for (uint8_t i = 0; i < 6; i ++)
		{
			if(mode) OLED_WriteData(~OLED_F6x8[Char - ' '][i]);
			else     OLED_WriteData(OLED_F6x8[Char - ' '][i]);
		}
	}
	else if (FontSize == 8)
	{
		OLED_SetCursor(X, Page);
		for (uint8_t i = 0; i < 8; i ++)
		{
			if(mode) OLED_WriteData(~OLED_F8x16[Char - ' '][i]);
			else		 OLED_WriteData(OLED_F8x16[Char - ' '][i]);
		}
		
		OLED_SetCursor(X, Page + 1);
		for (uint8_t i = 0; i < 8; i ++)
		{
			if(mode) OLED_WriteData(~OLED_F8x16[Char - ' '][i + 8]);
			else		 OLED_WriteData(OLED_F8x16[Char - ' '][i + 8]);
		}
	}
}

void OLED_ShowString(uint8_t X, uint8_t Page, char *String, uint8_t FontSize,uint8_t mode)
{
	for (uint8_t i = 0; String[i] != '\0'; i ++)
	{
		OLED_ShowChar(X + i * FontSize, Page, String[i], FontSize,mode);
	}
}

void OLED_ShowImage(uint8_t X, uint8_t Page, uint8_t Width, uint8_t Height, const uint8_t *Image,uint8_t mode)
{
	for (uint8_t j = 0; j < Height; j ++)
	{
		OLED_SetCursor(X, Page + j);
		for (uint8_t i = 0; i < Width; i ++)
		{
			if(mode) OLED_WriteData(~Image[Width * j + i]);
			else     OLED_WriteData(Image[Width * j + i]);
		}
	}
}

void OLED_ShowChinese(uint8_t X, uint8_t Page, char *Chinese, uint8_t mode)
{
	char SigleChinese[4] = {0};
	uint8_t pChinese = 0;
	uint8_t pIndex;
	
	for (uint8_t i = 0; Chinese[i] != '\0'; i ++)
	{
		SigleChinese[pChinese] = Chinese[i];
		pChinese ++;
		
		if (pChinese >= 3)
		{
			pChinese = 0;
			
			for (pIndex = 0; strcmp(OLED_CF16x16[pIndex].Index, "") != 0; pIndex ++)
			{
				if (strcmp(OLED_CF16x16[pIndex].Index, SigleChinese) == 0)
				{
					break;
				}
			}
			
			OLED_ShowImage(X + ((i + 1) / 3 - 1) * 16, Page, 16, 2, OLED_CF16x16[pIndex].Data, mode);
		}
	}
}

u32 OLED_Pow(u8 m,u8 n)
{
	u32 result=1;
	while(n--)
	{
	  result*=m;
	}
	return result;
}

void OLED_ShowNum(u8 x,u8 y,u32 num,u8 len,u8 size1,u8 mode)
{
	u8 t,temp,m=0;
	if(size1==8)m=4;
	for(t=0;t<len;t++)
	{
		temp=(num/OLED_Pow(10,len-t-1))%10;
			if(temp==0)
			{
				OLED_ShowChar(x+(size1/2+m)*t,y,'0',size1,mode);
      }
			else 
			{
			  OLED_ShowChar(x+(size1/2+m)*t,y,temp+'0',size1,mode);
			}
  }
} 

